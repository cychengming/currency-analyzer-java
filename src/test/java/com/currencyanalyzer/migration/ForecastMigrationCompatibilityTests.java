package com.currencyanalyzer.migration;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.MigrationVersion;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import static org.junit.jupiter.api.Assertions.assertTrue;

class ForecastMigrationCompatibilityTests {

    @Test
    void forecastMigrationAcceptsTablesCreatedByLegacyPythonApplication() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL(
            "jdbc:h2:mem:forecast_migration_compatibility;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1"
        );
        dataSource.setUser("sa");

        JdbcTemplate jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("""
            CREATE TABLE dl_forecast_runs (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                created_at VARCHAR(32) NOT NULL,
                model_type VARCHAR(32) NOT NULL,
                lookback_days INTEGER NOT NULL,
                horizon_days INTEGER NOT NULL,
                notes VARCHAR(256),
                asset VARCHAR(32)
            )
            """);
        jdbcTemplate.execute("""
            CREATE TABLE asset_forecast_daily (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                run_id INTEGER NOT NULL,
                dt VARCHAR(10) NOT NULL,
                predicted_close DOUBLE PRECISION NOT NULL,
                CONSTRAINT uq_asset_forecast_run_dt UNIQUE (run_id, dt)
            )
            """);
        jdbcTemplate.execute("""
            CREATE TABLE gold_forecast_daily (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                run_id INTEGER NOT NULL,
                dt VARCHAR(10) NOT NULL,
                predicted_close DOUBLE PRECISION NOT NULL,
                CONSTRAINT uq_gold_forecast_run_dt UNIQUE (run_id, dt)
            )
            """);
        jdbcTemplate.update("""
            INSERT INTO dl_forecast_runs
                (created_at, model_type, lookback_days, horizon_days, asset)
            VALUES ('2026-01-01', 'gru', 30, 7, 'GOLD/USD')
            """);

        Flyway.configure()
            .dataSource(dataSource)
            .locations("classpath:db/migration")
            .baselineOnMigrate(true)
            .baselineVersion(MigrationVersion.fromVersion("2"))
            .target(MigrationVersion.fromVersion("3"))
            .load()
            .migrate();

        assertTrue(jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM dl_forecast_runs WHERE asset = 'GOLD/USD'",
            Integer.class
        ) > 0);
        assertTrue(jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM information_schema.tables WHERE table_name = 'gold_forecast_daily'",
            Integer.class
        ) > 0);
    }
}
