CREATE TABLE ohlc_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair VARCHAR(32) NOT NULL,
    bar_date DATE NOT NULL,
    open_price DOUBLE PRECISION NOT NULL,
    high_price DOUBLE PRECISION NOT NULL,
    low_price DOUBLE PRECISION NOT NULL,
    close_price DOUBLE PRECISION NOT NULL,
    volume DOUBLE PRECISION NOT NULL DEFAULT 0,
    source VARCHAR(32) NOT NULL,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ohlc_history_pair_date UNIQUE (pair, bar_date),
    CONSTRAINT chk_ohlc_prices CHECK (
        open_price > 0 AND high_price >= low_price AND low_price > 0 AND close_price > 0
    )
);

CREATE INDEX idx_ohlc_history_pair_date ON ohlc_history (pair, bar_date);

CREATE TABLE policy_rate_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency VARCHAR(16) NOT NULL,
    effective_date DATE NOT NULL,
    annual_rate_pct DOUBLE PRECISION NOT NULL,
    source VARCHAR(32) NOT NULL,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_policy_rate_currency_date UNIQUE (currency, effective_date)
);

CREATE INDEX idx_policy_rate_currency_date ON policy_rate_history (currency, effective_date);

CREATE TABLE pipeline_backtest_runs (
    id UUID PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    profile_id VARCHAR(64) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    config_json TEXT NOT NULL,
    summary_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_pipeline_backtest_runs_user_created
    ON pipeline_backtest_runs (username, created_at DESC);
