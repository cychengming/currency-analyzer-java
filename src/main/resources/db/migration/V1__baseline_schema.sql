CREATE TABLE settings (
    key VARCHAR(255) PRIMARY KEY,
    value TEXT
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair VARCHAR(64),
    percent_change DOUBLE PRECISION,
    old_rate DOUBLE PRECISION,
    new_rate DOUBLE PRECISION,
    timestamp TIMESTAMP WITH TIME ZONE,
    email_sent BOOLEAN NOT NULL DEFAULT FALSE,
    alert_type VARCHAR(64),
    trigger_value DOUBLE PRECISION,
    threshold_value DOUBLE PRECISION
);

CREATE INDEX idx_alerts_timestamp_desc ON alerts (timestamp DESC);

CREATE TABLE monitoring_state (
    pair VARCHAR(64) PRIMARY KEY,
    last_alert_time TIMESTAMP WITH TIME ZONE
);

CREATE TABLE alert_preferences (
    pair VARCHAR(64) PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    alert_type VARCHAR(64) NOT NULL DEFAULT 'percentage_change',
    custom_threshold DOUBLE PRECISION,
    custom_period INTEGER,
    enable_trend_consistency BOOLEAN NOT NULL DEFAULT TRUE,
    lookback_years INTEGER NOT NULL DEFAULT 5,
    price_high DOUBLE PRECISION,
    price_low DOUBLE PRECISION,
    trigger_type VARCHAR(64),
    volatility_type VARCHAR(32),
    ma_short_period INTEGER NOT NULL DEFAULT 10,
    ma_long_period INTEGER NOT NULL DEFAULT 50,
    signal_type VARCHAR(64)
);

CREATE TABLE price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair VARCHAR(64) NOT NULL,
    date DATE NOT NULL,
    rate DOUBLE PRECISION NOT NULL,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_price_history_pair_date UNIQUE (pair, date)
);

CREATE INDEX idx_price_history_pair_date ON price_history (pair, date);

CREATE TABLE trade_journal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    pair VARCHAR(64) NOT NULL,
    side VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'open',
    entry_price DOUBLE PRECISION,
    stop_price DOUBLE PRECISION,
    close_price DOUBLE PRECISION,
    quantity DOUBLE PRECISION,
    risk_amount_usd DOUBLE PRECISION,
    risk_pct_of_equity DOUBLE PRECISION,
    atr DOUBLE PRECISION,
    sigma DOUBLE PRECISION,
    entry_reason TEXT,
    close_reason TEXT,
    notes TEXT,
    opened_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_trade_journal_user_opened
    ON trade_journal (username, opened_at DESC);

INSERT INTO settings (key, value)
SELECT defaults.key, defaults.value
FROM (
    SELECT 'trend_threshold' AS key, '2.0' AS value
    UNION ALL SELECT 'detection_period', '30'
    UNION ALL SELECT 'check_interval', '900'
    UNION ALL SELECT 'enable_alerts', 'true'
    UNION ALL SELECT 'enable_sound', 'true'
    UNION ALL SELECT 'alert_email', ''
    UNION ALL SELECT 'monitoring_enabled', 'false'
    UNION ALL SELECT 'daily_risk_limit_pct', '3.0'
) defaults
WHERE NOT EXISTS (
    SELECT 1 FROM settings existing WHERE existing.key = defaults.key
);
